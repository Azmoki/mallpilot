#!/usr/bin/env python3
"""Click store boundaries on the Elmina 1714x918 ground-floor image.

Trace points are recorded in native 1714x918 image pixels. The script scales
them when exporting Dart to the existing 1737x930 Flutter/backend routing
canvas; backend shop entrances, paths and service coordinates stay unchanged.
This assumes the new image is the same floor plan proportionally resized,
without cropping or rearranging shop positions.
Run within Frontend/ (or from any directory):

    python tools/trace_elmina_lots.py --list
    python tools/trace_elmina_lots.py --lot GF-01
    python tools/trace_elmina_lots.py --lot GF-03
    python tools/trace_elmina_lots.py --export

Requires: pip install opencv-python

Left-click successive corners of each store. Mouse-wheel zooms around the
cursor; hold RIGHT MOUSE BUTTON and drag to pan. Press F or 0 to reset zoom,
+/- to zoom using the screen center. Press N to SAVE the current polygon and
move to the NEXT store without reopening the map. Previously saved polygons
REMAIN VISIBLE on the map (green) and are never removed by advancing.
An empty polygon can be skipped with N. S/Enter saves without advancing;
U/Z undoes; R/C clears CURRENT outline only; Q/Esc exits (unsaved corners
are discarded). Stored outlines reload whenever you revisit a lot. The trace
order follows assets/data/shops.json. Flutter must be hot restarted after
exporting polygon changes.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / 'assets' / 'maps' / 'gf_light_map.png'
SHOPS = ROOT / 'assets' / 'data' / 'shops.json'
POLYGONS = ROOT / 'tools' / 'data' / 'elmina_polygons_GF.json'
DART = ROOT / 'lib' / 'lots_data.dart'
# Resolution of the actual floor-plan PNG used by this tracing tool.
EXPECTED_SIZE = (1714, 918)
# The backend routing graph and Flutter map canvas still use these dimensions.
# Do not change these unless you also migrate graph/facility coordinates.
FLUTTER_CANVAS_SIZE = (1737, 930)


def read_json(path: Path, default):
    return json.loads(path.read_text(encoding='utf-8')) if path.is_file() else default


def shop_by_lot(shops, candidate):
    lookup = candidate.strip().upper()
    for s in shops:
        identifiers = [s.get('primary_lot', ''), s.get('lot_id', '')]
        identifiers.extend(s.get('lots') or [])
        if lookup in (str(i).strip().upper() for i in identifiers):
            return s
    return None


def export_dart(polygons: dict, dest: Path = DART):
    """Generate Flutter's verified lots from separately recorded real boundaries."""
    lines = [
        "import 'package:flutter/material.dart';",
        "import 'indoor_map.dart';",
        '',
        '// GENERATED by tools/trace_elmina_lots.py. Edit polygon points in',
        '// tools/data/elmina_polygons_GF.json or rerun the picker, not here.',
        '// Traced on a 1714 x 918 image, scaled to the existing',
        '// 1737 x 930 Flutter/backend ground-floor canvas.',
        'final List<StoreLotAnchor> verifiedLotsData = [',
    ]
    count = 0
    for lot, entry in sorted(polygons.items()):
        corners = entry.get('corners', [])
        if len(corners) < 3:
            raise ValueError(f'{lot}: need at least three corners')
        if any(not isinstance(p, list) or len(p) != 2 or
               any(not isinstance(x, (int, float)) or isinstance(x, bool) for x in p)
               for p in corners):
            raise ValueError(f'{lot}: invalid coordinate list')
        if any(not (0 <= p[0] < EXPECTED_SIZE[0] and 0 <= p[1] < EXPECTED_SIZE[1])
               for p in corners):
            raise ValueError(f'{lot}: polygon point is outside the map')
        # JSON-escaped quoted strings are also valid Dart string literals.
        lines += [
            '  buildStoreLot(',
            f'    lotId: {json.dumps(lot, ensure_ascii=False)},',
            f'    name: {json.dumps(str(entry.get("name", lot)), ensure_ascii=False)},',
            f'    category: {json.dumps(str(entry.get("category", "General")), ensure_ascii=False)},',
            '    floor: "GF",',
            '    corners: const [',
        ]
        for x, y in corners:
            # Keep the existing backend graph coordinate system intact.
            # The map image fills the entire 1737x930 Flutter canvas.
            canvas_x = round(x * FLUTTER_CANVAS_SIZE[0] / EXPECTED_SIZE[0], 2)
            canvas_y = round(y * FLUTTER_CANVAS_SIZE[1] / EXPECTED_SIZE[1], 2)
            lines.append(f'      Offset({canvas_x}, {canvas_y}),')
        lines += ['    ],', '  ),']
        count += 1
    lines += ['];', '']
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text('\n'.join(lines), encoding='utf-8')
    return count


def tracing_sequence(shops):
    """Order stores as listed in the directory, avoiding duplicate polygon keys.

    Two shops in the uploaded directory share the primary lot GK-03. Using both
    entries as separate polygons would overwrite the first. The duplicate is
    reported and omitted until the shops data has unique route/lot identifiers.
    """
    sequence = []
    seen = {}
    duplicates = []
    for shop in shops:
        if shop.get('floor') != 'GF':
            continue
        lot = str(shop.get('primary_lot') or shop.get('lot_id') or '').strip()
        if not lot:
            continue
        key = lot.upper()
        if key in seen:
            duplicates.append((lot, seen[key], shop.get('name', '')))
            continue
        seen[key] = str(shop.get('name', ''))
        sequence.append(shop)
    return sequence, duplicates


class MapViewport:
    """Stable coordinate mapping between image pixels and an OpenCV viewport.

    Mouse clicks are converted back to ORIGINAL image coordinates; changing
    zoom/pan never changes the pixel coordinates written to polygon JSON.
    """

    def __init__(self, width: int, height: int, display_scale: float):
        self.width, self.height = width, height
        self.screen_width = max(1, math.ceil(width * display_scale))
        self.screen_height = max(1, math.ceil(height * display_scale))
        self.base_scale = display_scale
        self.max_scale = display_scale * 10
        self.reset()

    def reset(self):
        self.scale = self.base_scale
        self.x_offset = (self.screen_width - self.width * self.scale) / 2
        self.y_offset = (self.screen_height - self.height * self.scale) / 2
        self.clamp()

    def clamp(self):
        """Do not allow panning so far that the entire map disappears."""
        scaled_width = self.width * self.scale
        scaled_height = self.height * self.scale
        if scaled_width <= self.screen_width:
            self.x_offset = (self.screen_width - scaled_width) / 2
        else:
            self.x_offset = max(self.screen_width - scaled_width, min(0.0, self.x_offset))
        if scaled_height <= self.screen_height:
            self.y_offset = (self.screen_height - scaled_height) / 2
        else:
            self.y_offset = max(self.screen_height - scaled_height, min(0.0, self.y_offset))

    def to_image(self, x, y):
        px = round((x - self.x_offset) / self.scale)
        py = round((y - self.y_offset) / self.scale)
        if 0 <= px < self.width and 0 <= py < self.height:
            return (px, py)
        return None

    def to_screen(self, x, y):
        return (round(x * self.scale + self.x_offset),
                round(y * self.scale + self.y_offset))

    def zoom_at(self, factor: float, screen_x: float, screen_y: float):
        old_scale = self.scale
        new_scale = min(self.max_scale, max(self.base_scale, old_scale * factor))
        if abs(new_scale - old_scale) < 1e-9:
            return
        # Keep the ground-floor point under the mouse at the same screen position.
        image_x = (screen_x - self.x_offset) / old_scale
        image_y = (screen_y - self.y_offset) / old_scale
        self.scale = new_scale
        self.x_offset = screen_x - image_x * new_scale
        self.y_offset = screen_y - image_y * new_scale
        self.clamp()

    def pan(self, dx: float, dy: float):
        self.x_offset += dx
        self.y_offset += dy
        self.clamp()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument('--lot', help='Starting lot ID, e.g. GF-01; follows store directory order after this')
    parser.add_argument('--list', action='store_true', help='List known lots and store names in trace order')
    parser.add_argument('--export', action='store_true', help='Regenerate lots_data.dart from saved JSON without GUI')
    parser.add_argument('--scale', type=float, default=0.75,
                        help='Initial window size as a portion of the image (default: 0.75); zoom with mouse wheel')
    parser.add_argument('--image', type=Path, default=MAP, help='Elmina 1714x918 GF map image')
    args = parser.parse_args()

    shops = read_json(SHOPS, [])
    sequence, duplicates = tracing_sequence(shops)
    if args.list:
        for i, shop in enumerate(sequence, start=1):
            print(f"{i:>3}. {shop.get('primary_lot', shop.get('lot_id', '?')):<14} {shop.get('name', '')}")
        for lot, first, second in duplicates:
            print(f'WARNING: {lot} occurs for both {first!r} and {second!r}; second entry skipped to prevent overwriting.')
        return

    polygons = read_json(POLYGONS, {})
    if args.export:
        print(f'Exported {export_dart(polygons, DART)} polygons to {DART}')
        return

    if not args.lot:
        parser.error('Use --lot GF-01 to start tracing, --list, or --export')
    if args.scale <= 0 or args.scale > 2:
        parser.error('--scale must be > 0 and <= 2')
    if not sequence:
        parser.error('No ground-floor store IDs found in assets/data/shops.json')

    requested = shop_by_lot(shops, args.lot)
    if requested is None or requested.get('floor') != 'GF':
        parser.error(f'Unknown ground-floor lot {args.lot!r}; use --list for the available IDs')
    if requested not in sequence:
        parser.error(f'{args.lot!r} has a duplicate primary lot ID; fix this in shops.json before tracing it')
    current_index = sequence.index(requested)

    for lot, first, second in duplicates:
        print(f'WARNING: duplicate lot ID {lot}: {first!r} / {second!r}; skipped the second to avoid overwriting.')

    try:
        import cv2
        import numpy as np
    except ImportError:
        parser.error('Please install opencv-python: pip install opencv-python')

    image = cv2.imread(str(args.image), cv2.IMREAD_COLOR)
    if image is None:
        parser.error(f'Could not load the map image: {args.image}')
    h, w = image.shape[:2]
    if (w, h) != EXPECTED_SIZE:
        parser.error(f'Unexpected image size {w}x{h}; this tracer expects {EXPECTED_SIZE[0]}x{EXPECTED_SIZE[1]}.')

    viewport = MapViewport(w, h, args.scale)
    sw, sh = viewport.screen_width, viewport.screen_height
    # Keep the same OpenCV window and mouse handler throughout the session.
    window = 'Elmina Lakeside Mall - Store Polygon Tracer'
    cv2.namedWindow(window, cv2.WINDOW_AUTOSIZE)
    points = []
    is_panning = False
    last_mouse = (0, 0)

    def current_shop():
        return sequence[current_index]

    def current_lot():
        shop = current_shop()
        return str(shop.get('primary_lot') or shop.get('lot_id'))

    def load_current():
        lot = current_lot()
        points.clear()
        points.extend(tuple(p) for p in polygons.get(lot, {}).get('corners', []))
        print(f"[{current_index + 1}/{len(sequence)}] {lot} - {current_shop().get('name', '')} "
              f"({'already traced' if lot in polygons else 'not yet traced'})"
              f' | {len(polygons)} saved polygons shown in green.')

    def save_current():
        """Save the current shape, keeping ALL earlier saved shapes unchanged."""
        if len(points) < 3:
            print('Please mark at least 3 corners before saving.')
            return False
        area = abs(cv2.contourArea(np.array(points, dtype=np.float32)))
        if area < 10:
            print('Polygon area too small; please check the outline.')
            return False
        lot = current_lot()
        shop = current_shop()
        updated = dict(polygons)
        updated[lot] = {
            'name': str(shop.get('name', lot)),
            'category': str(shop.get('category', 'General')),
            'floor': 'GF',
            'corners': [list(p) for p in points],
        }
        # Regenerate Dart and JSON while retaining previously saved entries.
        try:
            export_dart(updated, DART)
            POLYGONS.parent.mkdir(parents=True, exist_ok=True)
            POLYGONS.write_text(json.dumps(updated, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        except (OSError, ValueError, TypeError) as err:
            print(f'Could not save {lot}: {err}')
            return False
        polygons.clear()
        polygons.update(updated)
        print(f'Saved {lot}: {len(points)} corners, {len(polygons)} polygons in total. '
              'Previous shapes are still saved and visible.')
        return True

    def mouse(event, x, y, flags, userdata):
        nonlocal is_panning, last_mouse
        if event == cv2.EVENT_LBUTTONDOWN:
            pixel = viewport.to_image(x, y)
            if pixel is not None:
                points.append(pixel)
        elif event == cv2.EVENT_RBUTTONDOWN:
            is_panning = True
            last_mouse = (x, y)
        elif event == cv2.EVENT_RBUTTONUP:
            is_panning = False
        elif event == cv2.EVENT_MOUSEMOVE and is_panning:
            viewport.pan(x - last_mouse[0], y - last_mouse[1])
            last_mouse = (x, y)
        elif event == cv2.EVENT_MOUSEWHEEL:
            # The Python OpenCV wheels flags encode a signed 16-bit delta
            # in the upper 16 bits; cv2.getMouseWheelDelta is unavailable in
            # some pip builds, including OpenCV 4.13.
            wheel_delta = (flags >> 16) & 0xFFFF
            if wheel_delta >= 0x8000:
                wheel_delta -= 0x10000
            if wheel_delta:
                viewport.zoom_at(1.25 if wheel_delta > 0 else 1 / 1.25, x, y)

    cv2.setMouseCallback(window, mouse)
    load_current()
    print('LEFT CLICK add corners | MOUSE WHEEL zoom | RIGHT DRAG pan | F/0 fit | +/- zoom')
    print('N saves + goes next (earlier polygons stay GREEN) | S save | U undo | R clear current | Q quit')
    print(f'Image {w}x{h}; Flutter exports at {FLUTTER_CANVAS_SIZE[0]}x{FLUTTER_CANVAS_SIZE[1]}.')

    def project(corners):
        return np.array([viewport.to_screen(x, y) for x, y in corners], dtype=np.int32)

    try:
        while True:
            # Render the original image in a fixed-size viewport using the
            # current pan and zoom. Coordinates in JSON are never zoomed.
            transform = np.float32([
                [viewport.scale, 0.0, viewport.x_offset],
                [0.0, viewport.scale, viewport.y_offset],
            ])
            frame = cv2.warpAffine(image, transform, (sw, sh),
                                   flags=cv2.INTER_LINEAR,
                                   borderMode=cv2.BORDER_CONSTANT,
                                   borderValue=(235, 235, 235))

            # Draw *all saved polygons from earlier stores*, not only the one
            # currently being traced. They remain visible after pressing N.
            earlier = []
            for lot_id, entry in polygons.items():
                if lot_id == current_lot():
                    continue  # Current one is drawn below, with corner handles.
                corners = entry.get('corners', [])
                if len(corners) >= 3:
                    earlier.append((lot_id, project(corners)))
            if earlier:
                green_overlay = frame.copy()
                cv2.fillPoly(green_overlay, [polygon for _, polygon in earlier], (95, 195, 85))
                frame = cv2.addWeighted(green_overlay, 0.28, frame, 0.72, 0)
                for lot_id, polygon in earlier:
                    cv2.polylines(frame, [polygon], True, (30, 125, 35), 2, cv2.LINE_AA)
                    center = np.mean(polygon, axis=0)
                    cx, cy = int(center[0]), int(center[1])
                    if 8 <= cx < sw - 80 and 38 <= cy < sh - 25:
                        cv2.putText(frame, lot_id, (cx, cy), cv2.FONT_HERSHEY_SIMPLEX,
                                    0.40, (20, 70, 20), 1, cv2.LINE_AA)

            # Current store is more strongly tinted and has numbered corners
            # to make it easy to edit, including after zooming.
            if points:
                projected = project(points)
                if len(projected) >= 3:
                    active_overlay = frame.copy()
                    cv2.fillPoly(active_overlay, [projected], (65, 225, 180))
                    frame = cv2.addWeighted(active_overlay, 0.35, frame, 0.65, 0)
                cv2.polylines(frame, [projected], isClosed=len(points) >= 3,
                              color=(25, 175, 45), thickness=2, lineType=cv2.LINE_AA)
                for number, (screen_x, screen_y) in enumerate(projected, start=1):
                    if -10 <= screen_x < sw + 10 and -10 <= screen_y < sh + 10:
                        cv2.circle(frame, (int(screen_x), int(screen_y)), 4, (25, 25, 255), -1)
                        cv2.putText(frame, str(number), (int(screen_x) + 5, int(screen_y) - 4),
                                    cv2.FONT_HERSHEY_SIMPLEX, 0.43, (0, 0, 0), 2, cv2.LINE_AA)

            # HUD: how many shapes remain on screen, which lot is active, zoom.
            cv2.rectangle(frame, (0, 0), (sw - 1, 32), (255, 255, 255), -1)
            shop = current_shop()
            label = f"{current_index + 1}/{len(sequence)} {current_lot()} - {shop.get('name', '')}"
            label = label[:55] + '...' if len(label) > 58 else label
            status = f"{label} | {len(points)} corners | {len(polygons)} saved | Zoom {viewport.scale / viewport.base_scale:.1f}x"
            cv2.putText(frame, status, (8, 22), cv2.FONT_HERSHEY_SIMPLEX,
                        0.47, (10, 20, 10), 1, cv2.LINE_AA)
            cv2.rectangle(frame, (0, sh - 29), (sw - 1, sh - 1), (255, 255, 255), -1)
            cv2.putText(frame, 'Wheel: zoom | Right drag: pan | F: fit | N: save + next | S: save | Q: exit',
                        (8, sh - 9), cv2.FONT_HERSHEY_SIMPLEX, 0.43, (10, 20, 10), 1, cv2.LINE_AA)
            cv2.imshow(window, frame)
            key = cv2.waitKey(30) & 0xFF

            if key in (ord('q'), ord('Q'), 27):
                stored = polygons.get(current_lot(), {}).get('corners', [])
                if [list(p) for p in points] != stored:
                    print('Exited without saving latest changes to this store; earlier saved polygons remain intact.')
                else:
                    print('Tracing session ended. All saved polygons are retained.')
                break
            elif key in (ord('z'), ord('Z'), ord('u'), ord('U')):
                if points:
                    points.pop()
            elif key in (ord('r'), ord('R'), ord('c'), ord('C')):
                points.clear()  # Does NOT remove already saved polygons.
            elif key in (ord('s'), ord('S'), 10, 13):
                save_current()
            elif key in (ord('n'), ord('N')):
                if points and not save_current():
                    continue  # Never silently discard an incomplete outline.
                if not points:
                    print(f'Skipped {current_lot()} (no corners added); existing saved lots stay unchanged.')
                if current_index + 1 == len(sequence):
                    print('Finished last store. All saved polygons remain in JSON and Dart.')
                    break
                current_index += 1
                load_current()  # Earlier polygons are shown by the renderer.
            elif key in (ord('f'), ord('F'), ord('0')):
                viewport.reset()
            elif key in (ord('+'), ord('=')):
                viewport.zoom_at(1.25, sw / 2, sh / 2)
            elif key in (ord('-'), ord('_')):
                viewport.zoom_at(1 / 1.25, sw / 2, sh / 2)
    finally:
        cv2.destroyAllWindows()


if __name__ == '__main__':
    main()
